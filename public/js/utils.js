//  Единая «библиотечная» реализация escapeHtml (P0, унификация).
//  Раньше в проекте жило 13 разных копий этой функции — от корректных
//  до экранирующих только &<> — из-за чего в атрибутах тегов можно было
//  вырваться через кавычку. Теперь все страницы подключают этот файл
//  и используют единственную каноничную версию.
//
//  Требования к подключению: <script src="/js/utils.js"></script>
//  должен идти РАНЬШЕ скриптов, использующих escapeHtml()
//  (app.js, header.js и инлайн-скрипты страниц).
// ═══════════════════════════════════════════════════════════════

'use strict';

/**
 * Экранирует HTML-спецсимволы: & < > " '.
 * Безопасно и для текстового содержимого, и для значений атрибутов.
 * @param {*} str — любое значение; null/undefined дают пустую строку.
 * @returns {string}
 */
function escapeHtml(str) {
  if (str == null) return '';
  return String(str).replace(/[&<>"']/g, function (m) {
    switch (m) {
      case '&': return '&amp;';
      case '<': return '&lt;';
      case '>': return '&gt;';
      case '"': return '&quot;';
      case "'": return '&#39;';
      default:  return m;
    }
  });
}

// Классический скрипт: function-объявление верхнего уровня и так
// становится глобальной (window.escapeHtml). Экспортируем явно,
// чтобы имя не терялось даже внутри модульных обёрток в будущем.
if (typeof window !== 'undefined') {
  window.escapeHtml = escapeHtml;
}
